"""Typed wire protocol shared by the backend and the frontend.

This module is the *contract*. The TypeScript mirror lives in
``frontend/lib/protocol.ts`` and the JSON Schema export in
``shared/schemas/protocol.schema.json`` (generated by
``scripts/export_schemas.py``; a test fails if it is stale).

Rules:
* Every field is JSON-serialisable; no private Python objects cross the wire.
* Timestamps are Unix epoch **milliseconds** (float) so browser
  ``performance.timeOrigin + performance.now()`` values compare directly.
* Bounding boxes are ``[x, y, w, h]`` normalised to the source frame (0..1).
"""

from __future__ import annotations

from enum import Enum
from typing import Annotated, Any, Literal, Union

from pydantic import BaseModel, ConfigDict, Field

PROTOCOL_VERSION = "1.0.0"


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", use_enum_values=True)


# --------------------------------------------------------------------------- #
# Enumerations
# --------------------------------------------------------------------------- #


class RegionName(str, Enum):
    lips = "lips"
    left_eye = "left_eye"
    right_eye = "right_eye"
    nose = "nose"
    skin_forehead = "skin_forehead"
    skin_left_cheek = "skin_left_cheek"
    skin_right_cheek = "skin_right_cheek"


class PipelineStage(str, Enum):
    camera_capture = "camera_capture"
    image_quality = "image_quality"
    face_detection = "face_detection"
    landmark_extraction = "landmark_extraction"
    region_cropping = "region_cropping"
    preprocessing = "preprocessing"
    cv_inference = "cv_inference"
    structured_observations = "structured_observations"
    llm_request = "llm_request"
    response_validation = "response_validation"
    ui_render = "ui_render"


PIPELINE_ORDER: list[str] = [s.value for s in PipelineStage]


class StageStatus(str, Enum):
    ok = "ok"
    warning = "warning"
    error = "error"
    skipped = "skipped"


class ModelTier(str, Enum):
    """How much a model's output may be trusted.

    * ``demo`` – trained on synthetic data only. Exercises the pipeline; its
      outputs are NOT observations about a real face.
    * ``validated`` – has an evaluation report on appropriately sourced,
      labelled data (still not clinical validation).
    * ``unavailable`` – no weights loaded.
    """

    demo = "demo"
    validated = "validated"
    unavailable = "unavailable"


class Decision(str, Enum):
    accepted = "accepted"  # top-class probability >= threshold, quality OK
    inconclusive = "inconclusive"  # below threshold
    abstained = "abstained"  # quality gate refused to classify
    unavailable = "unavailable"  # no model loaded


class QualityStatus(str, Enum):
    acceptable = "acceptable"
    poor = "poor"
    unusable = "unusable"


# --------------------------------------------------------------------------- #
# Telemetry
# --------------------------------------------------------------------------- #


class TelemetryEvent(_Model):
    session_id: str
    frame_id: int = Field(description="Monotonic per-session frame identifier. -1 for non-frame events (e.g. chat).")
    stage: PipelineStage
    status: StageStatus
    origin: Literal["client", "server"]
    started_at: float = Field(description="Epoch ms")
    duration_ms: float
    input_type: str
    output_type: str
    model_id: str | None = None
    model_version: str | None = None
    message: str | None = None
    seq: int = Field(0, description="Per-origin monotonic sequence number used to verify ordering")


# --------------------------------------------------------------------------- #
# Image quality
# --------------------------------------------------------------------------- #


class QualityMetrics(_Model):
    brightness: float | None = Field(None, description="Mean luma 0..255")
    contrast: float | None = Field(None, description="Luma std-dev")
    sharpness: float | None = Field(None, description="Variance of Laplacian on downscaled gray")
    face_area_fraction: float | None = None
    yaw_deg: float | None = None
    pitch_deg: float | None = None
    face_count: int | None = None


class ImageQuality(_Model):
    status: QualityStatus
    issues: list[str] = Field(default_factory=list)
    metrics: QualityMetrics = Field(default_factory=QualityMetrics)


# --------------------------------------------------------------------------- #
# Models
# --------------------------------------------------------------------------- #


class ModelInfo(_Model):
    model_id: str
    version: str
    tier: ModelTier
    feature: str = Field(description="Observable feature, e.g. 'visible_dryness'")
    regions: list[RegionName]
    classes: list[str]
    positive_class: str
    input_size: int
    normalization: dict[str, list[float]]
    backbone: str
    runtime: Literal["torch", "onnx", "none"]
    default_threshold: float
    explainable: bool
    status_message: str
    training_summary: dict[str, Any] = Field(default_factory=dict)
    metrics: dict[str, Any] = Field(default_factory=dict)


class TensorStats(_Model):
    shape: list[int]
    dtype: str
    channel_mean: list[float]
    channel_std: list[float]
    min: float
    max: float


class ModelInput(_Model):
    raw_size: list[int] = Field(description="[w, h] of the received crop in pixels")
    raw_preview_b64: str | None = Field(None, description="The received crop (JPEG data URL)")
    tensor_preview_b64: str | None = Field(None, description="De-normalised model input tensor rendered losslessly (PNG data URL)")
    tensor: TensorStats
    transforms: list[str]


class Prediction(_Model):
    model_id: str
    model_version: str
    model_tier: ModelTier
    region: RegionName
    feature: str
    classes: list[str]
    probabilities: list[float]
    top_class: str | None
    top_probability: float | None
    positive_probability: float | None
    threshold: float
    decision: Decision
    decision_reason: str
    latency_ms: float
    input: ModelInput | None = None


# --------------------------------------------------------------------------- #
# Structured observations — the ONLY CV-derived content the LLM sees.
# --------------------------------------------------------------------------- #


class Observation(_Model):
    region: RegionName
    feature: str
    confidence: float | None = Field(description="Classifier score for the positive class, aggregated over recent frames. NOT a probability of any medical condition.")
    status: Literal["accepted", "inconclusive", "abstained", "unavailable"]
    present: bool | None = Field(description="True if the accepted top class is the positive (visible-feature) class")
    model_id: str
    model_version: str
    model_tier: ModelTier
    frames_aggregated: int


class StructuredObservations(_Model):
    image_quality: QualityStatus
    quality_issues: list[str] = Field(default_factory=list)
    observations: list[Observation]
    user_reported_symptoms: list[str] = Field(default_factory=list)
    medical_diagnosis_requested: bool = False
    demo_mode: bool = Field(description="True if any contributing model is demo-tier (synthetic training data)")
    generated_at: float


# --------------------------------------------------------------------------- #
# WebSocket messages
# --------------------------------------------------------------------------- #


class RegionCrop(_Model):
    region: RegionName
    bbox: list[float] = Field(min_length=4, max_length=4, description="[x,y,w,h] normalised to the video frame")
    image_b64: str = Field(description="JPEG/PNG data URL or bare base64 of the cropped region")


class FrameOptions(_Model):
    return_inputs: bool = Field(False, description="Include raw/tensor previews (Model Lab)")
    thresholds: dict[str, float] = Field(default_factory=dict, description="Per-model threshold overrides")
    enabled_models: list[str] | None = None


class ClientHello(_Model):
    type: Literal["hello"] = "hello"
    session_id: str | None = None
    protocol_version: str = PROTOCOL_VERSION
    consent_upload_crops: bool = Field(description="User explicitly opted in to sending cropped face regions to the server")


class ClientFrame(_Model):
    type: Literal["frame"] = "frame"
    frame_id: int
    captured_at: float
    quality: ImageQuality
    regions: list[RegionCrop]
    client_events: list[TelemetryEvent] = Field(default_factory=list)
    options: FrameOptions = Field(default_factory=FrameOptions)


class ClientExplain(_Model):
    type: Literal["explain"] = "explain"
    request_id: str
    model_id: str
    region: RegionName
    image_b64: str
    target_class: str | None = None


class ClientPing(_Model):
    type: Literal["ping"] = "ping"
    t: float


ClientMessage = Annotated[Union[ClientHello, ClientFrame, ClientExplain, ClientPing], Field(discriminator="type")]


class ServerHelloAck(_Model):
    type: Literal["hello_ack"] = "hello_ack"
    session_id: str
    protocol_version: str = PROTOCOL_VERSION
    models: list[ModelInfo]
    server_time: float
    max_queue: int


class InferenceResult(_Model):
    type: Literal["inference_result"] = "inference_result"
    session_id: str
    frame_id: int
    captured_at: float
    received_at: float
    completed_at: float
    queue_wait_ms: float
    image_quality: ImageQuality
    predictions: list[Prediction]
    observations: StructuredObservations
    events: list[TelemetryEvent]


class FrameDropped(_Model):
    type: Literal["frame_dropped"] = "frame_dropped"
    frame_id: int
    reason: Literal["superseded", "queue_full", "invalid", "no_consent"]


class Explanation(_Model):
    type: Literal["explanation"] = "explanation"
    request_id: str
    model_id: str
    model_version: str
    region: RegionName
    method: str
    target_class: str
    target_probability: float
    input_b64: str = Field(description="Model input (de-normalised) as PNG data URL")
    heatmap_b64: str = Field(description="Colourised attribution map, same size as input, PNG data URL")
    latency_ms: float
    caveat: str


class ServerMetrics(_Model):
    type: Literal["server_metrics"] = "server_metrics"
    t: float
    cpu_percent: float | None
    rss_mb: float | None
    frames_received: int
    frames_processed: int
    frames_dropped: int
    frames_rejected: int
    queue_depth: int
    device: str


class ServerPong(_Model):
    type: Literal["pong"] = "pong"
    t: float
    server_time: float


class ServerError(_Model):
    type: Literal["error"] = "error"
    code: str
    message: str
    request_id: str | None = None


ServerMessage = Annotated[
    Union[ServerHelloAck, InferenceResult, FrameDropped, Explanation, ServerMetrics, ServerPong, ServerError],
    Field(discriminator="type"),
]


# --------------------------------------------------------------------------- #
# Chat / agent
# --------------------------------------------------------------------------- #


class ChatMessage(_Model):
    role: Literal["user", "assistant"]
    content: str = Field(max_length=4000)


class ChatRequest(_Model):
    session_id: str
    messages: list[ChatMessage] = Field(min_length=1, max_length=40)
    user_reported_symptoms: list[str] = Field(default_factory=list, max_length=20)
    observations: StructuredObservations | None = Field(
        None, description="Fallback if the server holds no observations for this session (e.g. REST-only clients)."
    )


class AssistantReply(_Model):
    """Schema the LLM must produce (validated server-side)."""

    message: str = Field(description="Plain-language reply to the user")
    follow_up_questions: list[str] = Field(default_factory=list, max_length=3)
    referenced_observations: list[str] = Field(
        default_factory=list, description="'region:feature' keys of the observations the reply relies on"
    )
    evidence_sufficient: bool
    suggests_professional: bool


class TraceStep(_Model):
    name: str
    status: StageStatus
    duration_ms: float
    detail: dict[str, Any] = Field(default_factory=dict)


class ValidationCheck(_Model):
    name: str
    passed: bool
    detail: str = ""


class RetrievedDoc(_Model):
    doc_id: str
    title: str
    score: float
    review_status: str


class AgentTrace(_Model):
    provider: str
    model: str
    route: Literal["standard", "urgent_safety", "diagnosis_request", "insufficient_evidence", "fallback"]
    steps: list[TraceStep]
    evidence: StructuredObservations | None
    selected_evidence: list[str]
    retrieval: list[RetrievedDoc]
    context_preview: str = Field(description="Redacted preview of what was sent to the LLM")
    validation: list[ValidationCheck]
    attempts: int
    latency_ms: float
    usage: dict[str, int] = Field(default_factory=dict)


class ChatResponse(_Model):
    reply: AssistantReply
    trace: AgentTrace
    events: list[TelemetryEvent]


# --------------------------------------------------------------------------- #
# REST: single-image inference, sessions, longitudinal comparison
# --------------------------------------------------------------------------- #


class ImageInferenceRequest(_Model):
    session_id: str | None = None
    image_b64: str = Field(description="Full frame. Only sent with explicit consent.")
    landmarks: list[list[float]] = Field(description="478 x [x,y,z] normalised MediaPipe landmarks")
    consent_upload: bool
    options: FrameOptions = Field(default_factory=FrameOptions)


class SessionCreated(_Model):
    session_id: str
    created_at: float


class DeletionReport(_Model):
    deleted_snapshots: int
    deleted_files: int
    deleted_session_state: bool


class SnapshotCreate(_Model):
    history_id: str = Field(min_length=8, max_length=64, description="Random client-generated pseudonymous id")
    image_b64: str
    landmarks: list[list[float]]
    consent_store_images: bool
    consent_text_version: str
    session_id: str | None = None


class SnapshotSummary(_Model):
    snapshot_id: str
    history_id: str
    created_at: float
    quality: ImageQuality
    lighting: dict[str, float]
    observations: list[Observation]
    regions: list[RegionName]


class RegionComparison(_Model):
    region: RegionName
    before_b64: str
    after_b64: str
    diff_b64: str
    mean_abs_diff: float
    lighting_delta: float
    lighting_comparable: bool
    before_observation: Observation | None
    after_observation: Observation | None


class ComparisonResult(_Model):
    before: SnapshotSummary
    after: SnapshotSummary
    regions: list[RegionComparison]
    caveats: list[str]
